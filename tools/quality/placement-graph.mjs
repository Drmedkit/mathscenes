// placement-graph.mjs: the check-in graph of the lesson line. Units = the lessons of pages/lessons/topics.json (in
// that order); an edge pre -> post says how strongly lesson `post` rests on lesson `pre`, derived from the curriculum's
// topic links (math-curriculum-essentials/dependencies.json): role (component .9, foundation .75, transfer .45) x kind
// (required 1, recommended .6), multiplied along a path. A path may run through topics outside the lesson line, never
// through another lesson (that edge is then indirect). Only edges from an EARLIER lesson in the order are kept (the
// order is the prerequisite order; a later lesson never counts as a foundation). Also each lesson's `requires`.
//   node tools/quality/placement-graph.mjs      -> pages/lessons/placement/graph.json
// Same idea as kubo-curriculum/interactive/_levelup/placement/build_graph.mjs.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './load.mjs';

const ESS = process.env.ESSENTIALS || path.join(ROOT, '..', 'math-curriculum-essentials');
const topics = JSON.parse(fs.readFileSync(path.join(ROOT, 'pages', 'lessons', 'topics.json'), 'utf8')).filter(t => t.live !== false);
const deps = JSON.parse(fs.readFileSync(path.join(ESS, 'dependencies.json'), 'utf8'));
const ROLE = { component: 0.9, foundation: 0.75, transfer: 0.45 }, KIND = { required: 1, recommended: 0.6 };
const units = topics.map((t, i) => ({ id: t.slug, slug: t.slug, title: t.title, grade: Number(t.grade), order: i, topic: t.id }));
const unitOf = new Map(units.map(u => [u.topic, u.id]));
const orderOf = new Map(units.map(u => [u.id, u.order]));

const into = new Map();                                     // topic -> [{ from, w }] (strongest link per pair)
for (const d of deps) {
  if (d.from === d.to) continue;
  const w = (ROLE[d.role] ?? 0.5) * (KIND[d.kind] ?? 0.6);
  const list = into.get(d.to) ?? [];
  const old = list.find(x => x.from === d.from);
  if (old) old.w = Math.max(old.w, w); else list.push({ from: d.from, w });
  into.set(d.to, list);
}
const edges = [];
for (const u of units) {
  const best = new Map(), seen = new Map(), stack = [[u.topic, 1, 0]];
  while (stack.length) {
    const [t, w, depth] = stack.pop();
    for (const { from, w: lw } of into.get(t) ?? []) {
      const nw = w * lw;
      if (nw < 0.15 || depth > 6) continue;
      const owner = unitOf.get(from);
      if (owner === u.id) continue;
      if (owner) { if (nw > (best.get(owner) ?? 0)) best.set(owner, nw); continue; }
      if ((seen.get(from) ?? 0) >= nw) continue;
      seen.set(from, nw);
      stack.push([from, nw, depth + 1]);
    }
  }
  // the lesson's own `requires` (topic ids) count as required components
  for (const req of topics[u.order].requires ?? []) { const o = unitOf.get(req); if (o && o !== u.id) best.set(o, Math.max(best.get(o) ?? 0, 0.9)); }
  for (const [p, w] of best) if (orderOf.get(p) < u.order) edges.push({ pre: p, post: u.id, w: Math.round(w * 100) / 100 });
}
const out = {
  _doc: 'Generated by tools/quality/placement-graph.mjs from math-curriculum-essentials/dependencies.json. pre -> post, w = evidence strength. Units in topics.json order.',
  units: units.map(({ id, slug, title, grade, order }) => ({ id, slug, title, grade, order })), edges,
};
fs.mkdirSync(path.join(ROOT, 'pages', 'lessons', 'placement'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'pages', 'lessons', 'placement', 'graph.json'), JSON.stringify(out, null, 1));
const indeg = new Map(units.map(u => [u.id, 0])); edges.forEach(e => indeg.set(e.post, indeg.get(e.post) + 1));
console.log(`${units.length} lessons, ${edges.length} edges, ${units.filter(u => !indeg.get(u.id)).length} without a prerequisite in the line`);
if (process.argv.includes('--list')) for (const u of units) console.log(String(u.order + 1).padStart(2), u.slug.padEnd(34), '<-', edges.filter(e => e.post === u.id).sort((a, b) => b.w - a.w).map(e => `${e.pre}(${e.w})`).join(' '));

// the catalogue names of every misconception id the lessons use (the check-in's end report)
const mcCat = new Map(JSON.parse(fs.readFileSync(path.join(ESS, 'misconceptions.json'), 'utf8')).misconceptions.map(m => [m.id, m.name]));
const used = new Set();
for (const u of units) {
  const f = path.join(ROOT, 'src', 'lesson', 'topics', u.slug, 'items.ts');
  if (fs.existsSync(f)) for (const m of fs.readFileSync(f, 'utf8').matchAll(/'(mc\.[a-z0-9.-]+)'/g)) used.add(m[1]);
}
const names = Object.fromEntries([...used].sort().filter(id => mcCat.has(id)).map(id => [id, mcCat.get(id)]));
fs.writeFileSync(path.join(ROOT, 'pages', 'lessons', 'placement', 'mc-names.json'), JSON.stringify(names, null, 1));
console.log(`mc-names.json: ${Object.keys(names).length} misconception names (${[...used].filter(id => !mcCat.has(id)).length} ids not in the catalogue)`);
